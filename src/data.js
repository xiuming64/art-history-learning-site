function makePages(topicId, keywords) {
  return pageTitles[topicId].map((title, index) => {
    const pageNumber = index + 1;
    const pageCode = String(pageNumber).padStart(2, "0");

    return {
      id: `${topicId}-page${pageCode}`,
      topicId,
      pageNumber,
      title,
      image: `/art/${topicId}/page${pageCode}.png`,
      keywords,
    };
  });
}

